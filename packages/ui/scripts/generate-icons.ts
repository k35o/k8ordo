/**
 * Generates everything that follows from the icon files.
 *
 * Single source of truth:
 *   src/components/icons/<name>.tsx ──(this)──►
 *     src/components/icons/index.ts            the `@k8ordo/ui/icons` entry
 *     src/integrations/_shared/icon-names.ts   the names a generative-UI spec may use
 *     src/integrations/_shared/icon-map.ts     the component each name draws
 *
 * One file is one icon: `eye-closed.tsx` exports `EyeClosedIcon`, and a spec
 * calls it `eye-closed`. Adding an icon is adding its file and running this.
 *
 *   node scripts/generate-icons.ts            # write the three files
 *   node scripts/generate-icons.ts --check    # fail if any of them is stale
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = fileURLToPath(
  new URL('../src/components/icons/', import.meta.url),
);
const SHARED_DIR = fileURLToPath(
  new URL('../src/integrations/_shared/', import.meta.url),
);

// What the icons are built on, not icons themselves.
const NOT_ICONS = new Set(['base', 'line-icon']);
// These take a second prop (`status`, `direction`) that the catalog's `Icon`
// entry has no slot for, so the catalog lists each as an entry of its own.
const COMPOSITES = new Set(['alert', 'chevron']);

const HEADER = '// Generated by scripts/generate-icons.ts. Do not edit.\n';

const exportNameOf = (file: string): string =>
  `${file
    .split('-')
    .map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
    .join('')}Icon`;

const files = (await readdir(ICONS_DIR))
  .filter((entry) => entry.endsWith('.tsx') && !entry.endsWith('.stories.tsx'))
  .map((entry) => entry.slice(0, -'.tsx'.length))
  .filter((file) => !NOT_ICONS.has(file))
  .toSorted();

await Promise.all(
  files.map(async (file) => {
    const source = await readFile(`${ICONS_DIR}${file}.tsx`, 'utf8');
    if (!source.includes(`export const ${exportNameOf(file)}:`)) {
      throw new Error(
        `src/components/icons/${file}.tsx must export ${exportNameOf(file)}.`,
      );
    }
  }),
);

const shapes = files.filter((file) => !COMPOSITES.has(file));
const key = (name: string): string => (name.includes('-') ? `'${name}'` : name);

const outputs: ReadonlyArray<readonly [path: string, content: string]> = [
  [
    `${ICONS_DIR}index.ts`,
    [
      HEADER,
      "export { BaseIcon } from './base';",
      "export type { BaseIconProps, IconRenderProps } from './base';",
      ...files.map(
        (file) => `export { ${exportNameOf(file)} } from './${file}';`,
      ),
      '',
    ].join('\n'),
  ],
  [
    `${SHARED_DIR}icon-names.ts`,
    [
      HEADER,
      'export const ICON_NAMES = [',
      ...shapes.map((file) => `  '${file}',`),
      '] as const;',
      '',
    ].join('\n'),
  ],
  [
    `${SHARED_DIR}icon-map.ts`,
    [
      HEADER,
      ...shapes.map(
        (file) =>
          `import { ${exportNameOf(file)} } from '../../components/icons/${file}';`,
      ),
      '',
      'export const iconMap = {',
      ...shapes.map((file) => `  ${key(file)}: ${exportNameOf(file)},`),
      '};',
      '',
    ].join('\n'),
  ],
];

if (process.argv.includes('--check')) {
  const stale = (
    await Promise.all(
      outputs.map(async ([path, content]) =>
        (await readFile(path, 'utf8').catch(() => '')) === content
          ? []
          : [path],
      ),
    )
  ).flat();
  if (stale.length > 0) {
    console.error(`Stale: ${stale.join(', ')}. Run \`pnpm generate:props\`.`);
    process.exit(1);
  }
  console.warn('The icon entry and the catalog icon list are in sync.');
} else {
  await Promise.all(outputs.map(([path, content]) => writeFile(path, content)));
  console.warn(
    `Wrote ${files.length} icons to the entry, ${shapes.length} to the catalog.`,
  );
}
